/**
 * Generates src/data/products.ts from the storefront catalog snapshot
 * (scripts/catalog.json), which was captured from piuraswim.com's public
 * product data. Curated fit language lives separately in src/data/fit.ts
 * so generated and hand-written data never mix.
 *
 * Run: node scripts/build-products.mjs
 */
import { readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';

const IN = path.resolve(process.cwd(), 'scripts/catalog.json');
const OUT = path.resolve(process.cwd(), 'src/data/products.ts');

const raw = JSON.parse(await readFile(IN, 'utf8'));

const normalizeSize = (s) => {
  const map = { small: 'S', medium: 'M', large: 'L', xl: 'XL', 'x-large': 'XL' };
  return map[String(s).toLowerCase()] ?? s;
};

const products = raw.map((p) => ({
  handle: p.handle,
  title: p.title,
  price: p.price,
  category: p.category,
  collection: p.collection,
  justDropped: (p.collectionHandles ?? []).includes('just-dropped'),
  pairsWith: p.pairsWith,
  sizes: p.sizes.map(normalizeSize),
  available: p.available.map(normalizeSize),
  images: p.images.map((name) => `products/${name.replace(/\.[a-z]+$/i, '')}.webp`),
  description: p.description,
  fitNotes: p.fitNotes ?? [],
  fabric: p.fabric ?? [],
}));

const source = `// Generated by scripts/build-products.mjs from scripts/catalog.json. Do not edit by hand.
// Source: public product data on piuraswim.com (titles, prices, sizes, availability,
// descriptions, fit notes and fabric copy are verbatim from the storefront).

import type { ImageKey } from './image-manifest';

export type Size = 'S' | 'M' | 'L' | 'XL';
export type Category = 'tops' | 'bottoms';
export type CollectionKey = 'sunchild' | 'moonchild' | 'classics';

export type Product = {
  handle: string;
  title: string;
  price: number;
  category: Category;
  collection: CollectionKey;
  justDropped: boolean;
  pairsWith: string;
  sizes: Size[];
  available: Size[];
  images: ImageKey[];
  description: string;
  fitNotes: string[];
  fabric: string[];
};

export const PRODUCTS: Product[] = ${JSON.stringify(products, null, 2)};
`;

await writeFile(OUT, source);
console.log(`Wrote ${products.length} products to ${path.relative(process.cwd(), OUT)}`);
