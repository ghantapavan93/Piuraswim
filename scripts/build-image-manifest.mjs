/**
 * Generates src/data/image-manifest.ts from public/images/piura.
 * Every image gets its intrinsic width and height so <Image> can reserve
 * space and avoid layout shift without static imports for 100+ files.
 *
 * Run: node scripts/build-image-manifest.mjs
 */
import { readdir, stat, writeFile } from 'node:fs/promises';
import path from 'node:path';
import sharp from 'sharp';

const ROOT = path.resolve(process.cwd(), 'public/images/piura');
const OUT = path.resolve(process.cwd(), 'src/data/image-manifest.ts');

async function walk(dir) {
  const entries = await readdir(dir, { withFileTypes: true });
  const files = [];
  for (const entry of entries) {
    const full = path.join(dir, entry.name);
    if (entry.isDirectory()) files.push(...(await walk(full)));
    else if (/\.(jpe?g|png|webp|avif|svg)$/i.test(entry.name)) files.push(full);
  }
  return files;
}

const files = (await walk(ROOT)).sort();
const entries = [];
for (const file of files) {
  const { width, height } = await sharp(file).metadata();
  const { size } = await stat(file);
  const publicPath = '/' + path.relative(path.resolve(process.cwd(), 'public'), file).split(path.sep).join('/');
  entries.push({ key: path.relative(ROOT, file).split(path.sep).join('/'), src: publicPath, width, height, bytes: size });
}

const lines = entries.map(
  (e) => `  ${JSON.stringify(e.key)}: { src: ${JSON.stringify(e.src)}, width: ${e.width}, height: ${e.height} },`
);

const source = `// Generated by scripts/build-image-manifest.mjs. Do not edit by hand.
// Intrinsic sizes for every image under public/images/piura.

export type ImageAsset = { src: string; width: number; height: number };

export const IMAGES = {
${lines.join('\n')}
} as const satisfies Record<string, ImageAsset>;

export type ImageKey = keyof typeof IMAGES;

export function image(key: ImageKey): ImageAsset {
  return IMAGES[key];
}
`;

await writeFile(OUT, source);
console.log(`Wrote ${entries.length} entries to ${path.relative(process.cwd(), OUT)}`);
